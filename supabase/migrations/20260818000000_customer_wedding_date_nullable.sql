-- =========================================================================
-- customers.wedding_date 를 NULL 허용으로 바꾼다
-- =========================================================================
-- 실제 업무 순서는 "네이버 스마트스토어 주문 접수 → 주문자 이름으로 고객 생성 →
-- 정보 수집 폼 발급" 이고, 이 시점에는 예식일을 모르는 경우가 많다. 예식일은 그
-- 다음 단계에서 고객이 폼에 직접 입력하고 /api/form-submit 이 customers 로
-- 되돌려 쓴다.
--
-- 그런데 이 컬럼이 NOT NULL 이라 고객 등록 화면이 "등록일 + 90일" 을 예식일로
-- 지어내 넣고 있었다. 그 값이 고객 목록의 "예식일시" 칼럼과 폼 발행 화면에 진짜
-- 날짜처럼 표시됐고, 더 나쁘게는 폼 링크 만료일(예식일 + 7일)과 보관기간 파기
-- 판정의 기준이 되어 실제 예식보다 먼저 폼이 닫히는 경우가 생길 수 있었다.
--
-- 예식일을 모르면 비워두는 게 맞다. 이 컬럼을 읽는 쪽은 이미 전부 "없으면 건너뛴다"
-- 로 되어 있다 — 파기 크론은 wedding_date 가 없으면 만료 판정 자체를 하지 않고
-- (§app/api/cron/purge-expired-invitations), 신랑신부 대시보드의 daysSince()도
-- null 을 반환해 만료·파기를 실행하지 않는다.
--
-- 기존에 쌓인 가짜 날짜는 건드리지 않는다. 어떤 게 지어낸 값이고 어떤 게 실제로
-- 입력된 값인지 사후에 구분할 방법이 없어서(둘 다 그냥 date 다), 임의로 지우면
-- 멀쩡한 예식일까지 날릴 수 있다. 필요하면 담당자가 화면에서 개별로 정정한다.

ALTER TABLE public.customers ALTER COLUMN wedding_date DROP NOT NULL;
